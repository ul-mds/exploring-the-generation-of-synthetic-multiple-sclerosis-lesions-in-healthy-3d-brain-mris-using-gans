"""" 
Script processes the gan2 results in inference. 
3D Images are reconstructed from 2D slices generated by GAN2.
And postprocessing is applied to the reconstructed images.
Postprocessing includes:
 * Gaussian smoothing in the direction, in which the images were sliced. 
    with sigma = 1
"""
from html import parser
import numpy as np
import nibabel as nib
import argparse
from pathlib import Path
from scipy.ndimage import gaussian_filter1d


def reconstruct_3d_from_slices(slice_dir, reference_flair_path, output_path, basename, lsmask_path):
    """ 
    Reconstructs a 3D NIfTI image from sorted 2D numpy arrays (gan2 output).
    The slices are expected to be named with the given prefix and sorted by their index. Reference NIfTI
    is used to set the shape, affine and header of the output image aswell as the slices, which do not contain 
    lesionvoxels and therefore were not generated by gan2. It's important to have dialated_lesionmasks as a reference,
     as the slices chosen for gan2 input are also based on dialated masks. 
     arguments:
    - slice_dir: Directory containing the gan2 generated slices.
    - reference_flair_path: Path to the reference FLAIR NIfTI image.
    - output_path: Path where the reconstructed 3D NIfTI image will be saved.
    - prefix: Prefix used for the gan2 generated slice filenames.
    - ref_mask_path: Path to the reference lesion mask NIfTI image, used to check which slices contain lesion voxels (has to be dialated!).
     """
    
    # original flair and lesion_mask (3d before slicing)
    # make sure lesion_mask is dialated, if not, dialate it here!
    ref_flair_img = nib.load(str(reference_flair_path))
    ref_flair_data = ref_flair_img.get_fdata().astype(ref_flair_img.get_data_dtype())
    lesion_data = nib.load(str(lsmask_path)).get_fdata()

    # new empty 3d image to fill with slices
    new_3d = np.zeros(ref_flair_data.shape, dtype=ref_flair_data.dtype)

    img_index = 0
    for i in range(ref_flair_data.shape[0]): 
        flair_slice = ref_flair_data[i, : , :]
        lesion_slice = lesion_data[i, : , :].astype(int)

        # check if lesion voxels in this slice, if yes, gan2 generated a slice for it.
        if np.any(lesion_slice): 
            # load the corresponding gan2 slice
            gan2_slice_npy = Path(slice_dir) / f"{basename}_flair_slice_{img_index:03d}_fake_B.npy"	
            if gan2_slice_npy.exists():
                # load the slice as numpy array from npy
                arr = np.load(gan2_slice_npy)
                img_index += 1
            else:
                print(f"Warning: Slice {gan2_slice_npy} was expected but does not exist.")
                return None
            new_3d[i, :, :] = arr

        else: 
            # copy the slice from the reference image
            new_3d[i, :, :] = flair_slice

    # create a new NIfTI image with the reconstructed 3D volume
    output_path = Path(output_path) 
    output_path.parent.mkdir(parents=True, exist_ok=True)
    img = nib.Nifti1Image(new_3d, affine=ref_flair_img.affine, header=ref_flair_img.header)
    nib.save(img, str(output_path))
    
    print(f"Reconstructed 3D NIfTI saved to {output_path}")


def apply_gaussian_smoothing(reconstructed_img, output_path, basename, ls_mask_path):
    """
    Applies gaussian smoothing, saves the result in output_path / "postprocessed". 
    """

    flair_img = nib.load(reconstructed_img)
    mask_img = nib.load(ls_mask_path)

    flair = flair_img.get_fdata()
    mask = mask_img.get_fdata() > 0.5

    smoothed = gaussian_filter1d(flair, sigma=1, axis=0)
    flair_post = flair.copy()
    flair_post[mask] = smoothed[mask]

    out_path = output_path / "postprocessed" / f"{basename}_flair_synth_lesions_postprocessed.nii.gz"
    nib.save(nib.Nifti1Image(flair_post, flair_img.affine, flair_img.header), out_path)
    print(f"Ergebnis gespeichert als {out_path}")


argument_parser = argparse.ArgumentParser(description='Reconstruct 3D NIfTI from GAN2 slices')
argument_parser.add_argument('--slices_dir', type=str, required=True, help='Directory containing the GAN2 generated slices.')
argument_parser.add_argument('--reference_flair_path', type=str, required=True, help='Path to the reference FLAIR NIfTI image.')
argument_parser.add_argument('--output_path', type=str, required=True, help='Path to the output directory for the reconstructed 3D NIfTI images.')
argument_parser.add_argument('--lsmasks_path', type=str, required=True, help='Path to the directory containing the lesion masks.')
argument_parser.add_argument('--gan1_epoch', type=str, required=True, help='Needed to complete path to GAN1 results.')
argument_parser.add_argument('--gan1_name', type=str, required=True, help='Needed to complete path to GAN1 results.')
argument_parser.add_argument('--gan1_phase', type=str, required=True, help='Needed to complete path to GAN1 results.')

args = argument_parser.parse_args()

lsmask_path = Path(args.lsmasks_path) / args.gan1_name / f"{args.gan1_phase}_{args.gan1_epoch}" / "images"

for flair_img in Path(args.reference_flair_path).glob("*.mgz"):
    basename = flair_img.stem.replace('_flair_mni_registered', '')
    reconstruct_3d_from_slices(
        slice_dir=Path(args.slices_dir),
        reference_flair_path=flair_img,
        output_path=Path(args.output_path) / f"{basename}_reconstructed.nii.gz",
        basename=basename,
        lsmask_path=lsmask_path / f"{basename}_fake_B.nii"
    )

# apply gaussian smoothing to the reconstructed 3D NIfTI images
for reconstructed_img in Path(args.output_path).glob("*_reconstructed.nii.gz"):
    basename = reconstructed_img.stem.replace('_reconstructed', '')
    apply_gaussian_smoothing(reconstructed_img, 
                             output_path=Path(args.output_path), 
                             basename=basename,
                             ls_mask_path=Path(args.lsmasks_path) / f"{basename}_source_gan1.nii_fake_B.nii"
    )
