""" 
Script calculates FID and the MSE between the lesion_heatmaps comparing synthetic lesion masks generated by gan1 and the reference lesion masks.
This is used to evaluate the hyperparameter training of gan1.
Results are saved as pickle for further analysis.
"""

from pathlib import Path
import os
import sys
import shutil
import pickle

sys.path.append(os.path.abspath(os.path.join(os.getcwd(), '..')))
from gan1_evaluation_class import LesionMetrics

REF_LSMSKS = Path("/home/sc.uni-leipzig.de/iu71daji/thesis_gan1/evaluation_results/registered_lesionmasks")
RESULTS_PATH = Path("/home/sc.uni-leipzig.de/iu71daji/thesis_gan1/evaluation_results/final_evaluation_results")
TEST_RESULTS_PATH = Path("/home/sc.uni-leipzig.de/iu71daji/thesis_gan1/testresults")
HYPERPARAM_PATH = Path("/home/sc.uni-leipzig.de/iu71daji/thesis_gan1/testresults/gan1_hyperparameters.txt")

def save_synthetic_masks(model_path):
    """" 
    Saves the synthetic lesion masks generated by gan1 in a separate folder.
    """   
    # synthetic lesionmasks
    gan1_results_path = model_path / "images"

    # save synthetic masks in seperate folder 
    target_dir = gan1_results_path.parent / "synthetic_lesionmasks"
    target_dir.mkdir(exist_ok=True)
    for img_path in gan1_results_path.glob("*fake_B.nii*"):
        shutil.copy(img_path, target_dir / img_path.name)
    return target_dir


RESULTS_PATH.mkdir(parents=True, exist_ok=True)
#load gan1 hyperparameters
hyperparams = []
with open(HYPERPARAM_PATH, 'r') as f:
    lines = f.read().splitlines()
    for line in lines:
        lambda_l1, lambda_l2 = line.split(' ')
        hyperparams.append((lambda_l1, lambda_l2))  
print(f"Hyperparameters: {hyperparams}")

results = {}
# load reference lesion masks
reference_data = LesionMetrics(ls_dir=REF_LSMSKS, dataset_name="eval_reference_lesionmasks", ls_suffix="_ls_mask_mni_registered.mgz")
reference_data._collect_basenames()
reference_data.compute_measures()

results["reference_data"] = reference_data.results_to_dict()

# load synthetic data
for hyperparam in hyperparams:
    lambda_l1, lambda_l2 = hyperparam
    for epoch in [150, 300, 450, 600]:
        # load synthetic lesion masks
        model_path = TEST_RESULTS_PATH / f"gan1_hyptr_L1_{lambda_l1}_L2_{lambda_l2}/test_{epoch}"
        synth_ls_path = save_synthetic_masks(model_path)
        synthetic_data = LesionMetrics(ls_dir=synth_ls_path, 
                                    dataset_name=f"gan1_results_L1_{lambda_l1}_L2_{lambda_l2}_epoch_{epoch}", 
                                    ls_suffix="_source_gan1.nii_fake_B.nii")
        synthetic_data._collect_basenames()
        synthetic_data.compute_measures()

        # calc frechet inception distance (FID)
        fid = reference_data.compare_distributions_fid(synthetic_data)

        # calc earth mover's distance (EMD)
        emds = reference_data.compare_distributions_emd(synthetic_data)
        
        # calc mse heatmap
        out_path = RESULTS_PATH / "heatmaps"
        out_path.mkdir(parents=True, exist_ok=True)
        synthetic_data.calc_lesion_heatmap(out_path=out_path, normalize=True)
        reference_data.calc_lesion_heatmap(out_path=out_path, normalize=True)

        mse_heatmap = reference_data.compare_heatmaps(synthetic_data)

        results[synthetic_data.dataset_name] = synthetic_data.results_to_dict(emds=emds,
                                                                            fid=fid,
                                                                            mse_heatmap=mse_heatmap)

# save results
results_path = RESULTS_PATH / "gan1_eval_hyperparam_training_results.pkl"
with open(results_path, 'wb') as f:
    pickle.dump(results, f)