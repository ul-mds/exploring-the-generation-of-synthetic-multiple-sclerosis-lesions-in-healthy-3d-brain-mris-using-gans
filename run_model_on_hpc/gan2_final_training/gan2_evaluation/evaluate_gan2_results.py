def reconstruct_3d_from_slices(slice_dir, reference_flair_path, output_path, prefix, ref_mask_path, fold):
    """ 
    Reconstructs a 3D NIfTI image from sorted 2D numpy arrays (gan2 output).
    The slices are expected to be named with the given prefix and sorted by their index. Reference NIfTI
    is used to set the shape, affine and header of the output image aswell as the slices, which do not contain 
    lesionvoxels and therefore were not generated by gan2. It's important to have dialated_lesionmasks as a reference,
     as the slices chosen for gan2 input are also based on dialated masks. 
     arguments:
    - slice_dir: Directory containing the gan2 generated slices.
    - reference_flair_path: Path to the reference FLAIR NIfTI image.
    - output_path: Path where the reconstructed 3D NIfTI image will be saved.
    - prefix: Prefix used for the gan2 generated slice filenames.
    - ref_mask_path: Path to the reference lesion mask NIfTI image, used to check which slices contain lesion voxels (has to be dialated!).
     """

    # original flair and lesion_mask (3d before slicing)
    # make sure lesion_mask is dialated, if not, dialate it here!
    ref_flair_img = nib.load(str(reference_flair_path))
    ref_flair_data = ref_flair_img.get_fdata().astype(ref_flair_img.get_data_dtype())
    lesion_data = nib.load(str(ref_mask_path)).get_fdata()

    # new empty 3d image to fill with slices
    new_3d = np.zeros(ref_flair_data.shape, dtype=ref_flair_data.dtype)

    img_index = 0
    for i in range(ref_flair_data.shape[0]): 
        flair_slice = ref_flair_data[i, : , :]
        lesion_slice = lesion_data[i, : , :]

        # check if lesion voxels in this slice, if yes, gan2 generated a slice for it.
        if np.any(lesion_slice): 
            # load the corresponding gan2 slice
            gan2_slice_png = Path(slice_dir) / f"{prefix}_flair_slice_{img_index:03d}_fake_B.png"
            gan2_slice_npy = Path(slice_dir) / f"{prefix}_flair_slice_{img_index:03d}_fake_B.npy"	
            if gan2_slice_npy.exists():
                # load the slice as numpy array from npy
                arr = np.load(gan2_slice_npy)
                img_index += 1
            # uncomment to allow loading from png instead of npy.
            #elif gan2_slice_npy.exists():
            #    # load the slice as numpy array from png
            #    arr = np.array(Image.open(gan2_slice_png))
            #    img_index += 1
            else:
                print(f"Warning: Slice {gan2_slice_png} or {gan2_slice_npy} was expected but does not exist.")
                return None
            new_3d[i, :, :] = arr

        else: 
            # copy the slice from the reference image
            new_3d[i, :, :] = flair_slice


    # create a new NIfTI image with the reconstructed 3D volume
    output_path = Path(output_path) 
    img = nib.Nifti1Image(new_3d, affine=ref_flair_img.affine, header=ref_flair_img.header)
    nib.save(img, str(output_path))
    
    print(f"Reconstructed 3D NIfTI saved to {output_path}")


def get_basename(center, patient):
    if center == "umcl" and isinstance(patient, str):
        num = ''.join(filter(str.isdigit, patient))
        return f"umcl_patient{int(num):02}"
    elif center == "msseg2" and isinstance(patient, str):
        return f"msseg2_patient{int(patient):03}"
    elif center == "msseg" and isinstance(patient, list) and len(patient) == 2:
        p, c = patient
        return f"msseg_patient{int(p):02}_center{int(c):02}"
    else:
        return f"{center}_patient{patient}"

def get_image_dict(training_path):
    """ 
    Loads the k_fold_patients.json file and creates a dictionary that maps each fold to a list of basenames.
    """
    with open((training_path / "k_fold_patients.json"), "r") as f:
        folds = json.load(f)

    # Dictionary: für jeden Fold eine Liste der Basenames
    basenames_per_fold = {}
    for fold, patients in folds.items():
        basenames_per_fold[fold] = [get_basename(center, patient) for center, patient in patients]
    return basenames_per_fold    

def calc_mse(output_path, reference_flair, ref_mask_path):
    """
    Calculates the MSE between the output image and the reference flair image.
    Also calculates the MSE for the area of the dilated lesion mask and the brain region.
    """
    # Load images
    output_img = nib.load(output_path).get_fdata()
    ref_flair_img = nib.load(reference_flair).get_fdata()
    ref_mask_img = nib.load(ref_mask_path).get_fdata()

    # Calculate MSE for the whole image
    mse_img = np.nanmean((ref_flair_img.flatten() - output_img.flatten()) ** 2)

    # Calculate MSE for the dilated lesion mask regions
    lesion_mask = ref_mask_img > 0
    mse_dialated_lsmask = np.nanmean((ref_flair_img[lesion_mask] - output_img[lesion_mask])**2)

    # Calculate MSE for the brain region
    brain_region = ref_flair_img > 0  # Assuming brain region is where the flair image has non-zero values
    mse_brain = np.nanmean((ref_flair_img[brain_region] - output_img[brain_region])**2)

    return mse_img, mse_dialated_lsmask, mse_brain

